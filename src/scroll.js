/**
 * Determina el tipo de dispositivo actual según el ancho de pantalla.
 * @returns {'mobile'|'tablet'|'desktop'}
 */
export function getDeviceType() {
  const width = window.innerWidth;
  if (width < 768) return 'mobile';
  if (width < 992) return 'tablet';
  return 'desktop';
}

/**
 * Obtiene la configuración de scroll activa para un canto y dispositivo.
 * Busca primero un valor guardado por el usuario y luego cae al valor por defecto.
 * @param {string} songId 
 * @returns {{v: number, i: number}} { v: intervalo_ms, i: paso_px }
 */
export function getSongScrollConfig(songId) {
  const device = getDeviceType();
  const customKey = `scroll-speed-${songId}-${device}`;
  
  // 1. Intentar cargar preferencia personalizada
  const custom = localStorage.getItem(customKey);
  if (custom) {
    try {
      return JSON.parse(custom);
    } catch (e) {
      console.warn("Error parseando velocidad personalizada para", songId, e);
    }
  }
  
  // 2. Caer a la configuración por defecto del canto
  const songDefault = defaultScrollConfigs[songId];
  if (songDefault && songDefault[device]) {
    return {
      v: songDefault[device].v || 40,
      i: songDefault[device].i || 1
    };
  }
  
  // 3. Fallback absoluto general si no hay configuración
  return { v: 40, i: 1 };
}

/**
 * Guarda la configuración de scroll personalizada por el usuario para un canto y dispositivo.
 * @param {string} songId 
 * @param {number} interval 
 * @param {number} step 
 */
export function saveSongScrollConfig(songId, interval, step) {
  const device = getDeviceType();
  const customKey = `scroll-speed-${songId}-${device}`;
  const config = { v: interval, i: step };
  localStorage.setItem(customKey, JSON.stringify(config));
}
